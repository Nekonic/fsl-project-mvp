import ast
import io
import re
import tokenize
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[3]
CODE_ROOTS = ("platform", "front/src", "bots", "bin", "test", "deploy", "wargames", "redteam")
NOT_SCANNED = re.compile(
    r"^deploy/suricata/rules/|^front/src/api/schema\.d\.ts$"
    r"|(?:^|/)(?:\.[^/]+|__pycache__|node_modules|dist)/")
SHEBANG = re.compile(r"#!\S")
DJANGO_MIGRATION_HEADER = re.compile(r"# Generated by Django \S+ on \d{4}-\d\d-\d\d \d\d:\d\d$")
SHELLS = re.compile(r"#!\s*(?:/usr/bin/env\s+)?(?:/bin/|/usr/bin/)?(?:ba|da|z)?sh\b")
PYTHONS = re.compile(r"#!\s*(?:/usr/bin/env\s+)?\S*python")
HEREDOC = re.compile(r"(?<!<)<<(?!<)-?\s*\\?(['\"]?)([A-Za-z_]\w*)\1")
PYTHON_COMMAND = re.compile(r"\bpython3?\b|\$\{?PY\b")
WORD_BREAKS = " \t;&|()"
SCRIPT_SUFFIXES = {".ts", ".tsx", ".js", ".jsx", ".mjs"}


def kind_of(path: Path) -> str | None:
    if path.suffix == ".py":
        return "python"
    if path.suffix == ".sh":
        return "shell"
    if path.suffix in SCRIPT_SUFFIXES:
        return "script"
    if path.suffix:
        return None
    first = path.read_text(errors="ignore").split("\n", 1)[0]
    if PYTHONS.match(first):
        return "python"
    if SHELLS.match(first):
        return "shell"
    return None


def is_migration(name: str) -> bool:
    return "/migrations/" in name


def python_comments(name: str, text: str) -> list[int]:
    found = []
    for token in tokenize.generate_tokens(io.StringIO(text).readline):
        if token.type != tokenize.COMMENT:
            continue
        line, _ = token.start
        if line == 1 and SHEBANG.match(token.string):
            continue
        if line == 1 and is_migration(name) and DJANGO_MIGRATION_HEADER.match(token.string):
            continue
        found.append(line)
    return found


def python_docstrings(text: str) -> list[int]:
    tree = ast.parse(text)
    holders = [tree, *(node for node in ast.walk(tree)
                       if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)))]
    return [holder.body[0].lineno for holder in holders
            if holder.body and isinstance(holder.body[0], ast.Expr)
            and isinstance(holder.body[0].value, ast.Constant) and isinstance(holder.body[0].value.value, str)]


def heredoc_opened(line: str) -> re.Match | None:
    for opened in HEREDOC.finditer(line):
        if "((" not in line[:opened.start()]:
            return opened
    return None


def shell_line_comment(line: str, quote: str | None) -> tuple[bool, str | None]:
    index = 0
    while index < len(line):
        char = line[index]
        if quote == "'":
            if char == "'":
                quote = None
        elif char == "\\":
            index += 2
            continue
        elif quote == '"':
            if char == '"':
                quote = None
        elif char in "'\"":
            quote = char
        elif char == "#" and (index == 0 or line[index - 1] in WORD_BREAKS):
            return True, quote
        index += 1
    return False, quote


def shell_comments(text: str) -> list[int]:
    lines = text.split("\n")
    heredoc = None
    found = []
    quote = None
    for number, line in enumerate(lines, start=1):
        if heredoc is not None:
            end, opened_at, python = heredoc
            if line.strip() == end:
                if python:
                    body = "\n".join(lines[opened_at:number - 1]) + "\n"
                    found.extend(opened_at + inner for inner in python_comments("heredoc", body))
                heredoc = None
            continue
        if number == 1 and SHEBANG.match(line):
            continue
        commented, quote = shell_line_comment(line, quote)
        if commented:
            found.append(number)
        opened = None if quote else heredoc_opened(line)
        if opened:
            heredoc = (opened.group(2), number, bool(PYTHON_COMMAND.search(line[:opened.start()])))
    return found


def script_comments(text: str) -> list[int]:
    found = []
    index, line, quote = 0, 1, None
    while index < len(text):
        char = text[index]
        ahead = text[index:index + 2]
        if char == "\n":
            line += 1
        if quote:
            if char == "\\":
                index += 2
                continue
            if char == quote:
                quote = None
        elif char in "'\"`":
            quote = char
        elif ahead == "//":
            found.append(line)
            index = text.find("\n", index)
            if index < 0:
                break
            continue
        elif ahead == "/*":
            found.append(line)
            closed = text.find("*/", index + 2)
            closed = len(text) if closed < 0 else closed + 2
            line += text.count("\n", index, closed)
            index = closed
            continue
        index += 1
    return found


def commented_lines(name: str, path: Path) -> list[str]:
    kind = kind_of(path)
    text = path.read_text(errors="ignore")
    if kind == "python":
        return ([f"{name}:{line} comment" for line in python_comments(name, text)]
                + [f"{name}:{line} docstring" for line in python_docstrings(text)])
    if kind == "shell":
        return [f"{name}:{line} comment" for line in shell_comments(text)]
    if kind == "script":
        return [f"{name}:{line} comment" for line in script_comments(text)]
    return []


def code_files() -> dict[str, Path]:
    files = {}
    for root in CODE_ROOTS:
        for path in sorted((REPO / root).rglob("*")):
            name = str(path.relative_to(REPO))
            if path.is_file() and not NOT_SCANNED.search(name) and kind_of(path):
                files[name] = path
    return files


def test_no_code_file_carries_a_comment_or_a_docstring():
    found = [where for name, path in code_files().items() for where in commented_lines(name, path)]

    assert found == []


def test_the_scan_reaches_python_shell_and_every_code_root():
    files = code_files()
    kinds = {kind_of(path) for path in files.values()}

    assert {"python", "shell"} <= kinds
    assert {"bin/verify", "bin/carry-users", "platform/entrypoint.sh", "bots/cli.py"} <= set(files)
    assert not [name for name in files if name.startswith("deploy/suricata/rules/")]


@pytest.mark.parametrize("text, lines", [
    ("x = 1\n# a note\n", [2]),
    ("x = 1  # a note\n", [1]),
    ("#!/usr/bin/env python3\nx = '#not a comment'\n", []),
])
def test_python_comments_are_tokens_not_hashes_in_strings(text, lines):
    assert python_comments("bin/x", text) == lines


def test_only_django_s_own_header_is_allowed_and_only_in_a_migration():
    header = "# Generated by Django 6.1.3 on 2026-11-19 15:37\nx = 1\n"

    assert python_comments("platform/accounts/migrations/0001_initial.py", header) == []
    assert python_comments("platform/users/accounts.py", header) == [1]


def test_docstrings_are_found_on_modules_classes_and_functions():
    text = '"""module"""\nclass A:\n    """class"""\ndef f():\n    """function"""\n    return "kept"\n'

    assert python_docstrings(text) == [1, 3, 5]


def test_shell_comments_skip_the_shebang_and_heredocs():
    text = "#!/usr/bin/env bash\n# note\ncat <<EOF\n# data\nEOF\necho \"$#\"\n"

    assert shell_comments(text) == [2]


@pytest.mark.parametrize("text, lines", [
    ("set -e\necho done # note\n", [2]),
    ("x=1; # note\n", [1]),
    ("echo '# kept' \"# kept\" ${#x} $# a\\#b\n", []),
    ("echo 'one\n# inside a string\n'\n", []),
    ("read -r a <<< \"$x\"\nread -r b <<< word\n# note\n", [3]),
    ("echo $((1 << 4))\n# note\n", [2]),
    ("cat<<EOF\n# data\nEOF\n# note\n", [4]),
    ("cat <<\\EOF\n# data\nEOF\n", []),
])
def test_shell_comments_find_trailing_ones_and_herestrings_do_not_hide_the_rest(text, lines):
    assert shell_comments(text) == lines


def test_python_fed_to_a_heredoc_is_scanned_as_python():
    text = "out=$(python - <<'PY'\nimport sys\n# note\nprint('#kept')\nPY\n)\ncat <<EOF\n# data\nEOF\n"

    assert shell_comments(text) == [3]


def test_script_comments_skip_strings_and_find_both_forms():
    text = "const a = 'http://x';\n// note\nconst b = `/* not */`;\n/* block\n */ const c = 1;\n"

    assert script_comments(text) == [2, 4]
