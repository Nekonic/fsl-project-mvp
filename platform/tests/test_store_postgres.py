ROOT = Path(__file__).resolve().parents[2]
PLATFORM = ROOT / "platform"
PASSWORD = "store-test"


def compose_image():
    return yaml.safe_load((ROOT / "compose.yaml").read_text())["services"]["postgres"]["image"]


def load_backup():
    loader = SourceFileLoader("backup_pg", str(ROOT / "bin/backup"))
    module = importlib.util.module_from_spec(importlib.util.spec_from_loader("backup_pg", loader))
    loader.exec_module(module)
    return module


def docker(*args, check=True):
    return subprocess.run(["docker", *args], capture_output=True, text=True, check=check)


@pytest.fixture(scope="module")
def store():
    if shutil.which("docker") is None or docker("info", check=False).returncode != 0:
        pytest.skip("no Docker here to run the store's PostgreSQL image")
    name = f"cr-store-test-{uuid.uuid4().hex[:8]}"
    docker("run", "-d", "--rm", "--name", name, "-e", "POSTGRES_USER=cr", "-e", "POSTGRES_DB=cr",
           "-e", f"POSTGRES_PASSWORD={PASSWORD}", "-p", "127.0.0.1::5432", compose_image())
    try:
        for _ in range(120):
            if docker("exec", name, "pg_isready", "-q", "-h", "127.0.0.1", "-U", "cr", "-d", "cr",
                      check=False).returncode == 0:
                break
            time.sleep(0.5)
        else:
            pytest.fail(f"{name} never accepted connections")
        port = docker("port", name, "5432/tcp").stdout.split()[0].rsplit(":", 1)[1]
        yield name, port
    finally:
        docker("rm", "-f", name, check=False)


def psql(name, sql, database="cr"):
    return docker("exec", name, "psql", "-X", "-q", "-At", "-v", "ON_ERROR_STOP=1", "-U", "cr", "-d", database,
                  "-c", sql).stdout.strip()


def fresh_database(name):
    database = f"t{uuid.uuid4().hex[:10]}"
    psql(name, f"CREATE DATABASE {database}")
    return database


def way_in(name, database):
    return shlex.join(["docker", "exec", "-i", "-e", f"POSTGRES_DB={database}", name, "bash", "-s"])


def backed_up(monkeypatch, tmp_path, *asked):
    module = load_backup()
    monkeypatch.setattr(module, "BACKUPS", tmp_path / "backups")
    monkeypatch.setattr(sys, "argv", ["backup", *asked])
    module.main()
    return module


def test_a_store_dumped_while_serving_comes_back_whole_after_it_changed(store, monkeypatch, tmp_path, capsys):
    name, _ = store
    database = fresh_database(name)
    psql(name, "CREATE TABLE auth_user (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username text); "
               "INSERT INTO auth_user (username) VALUES ('staff'), ('learner'); "
               "CREATE TABLE telemetry_detection (id bigint PRIMARY KEY, raw jsonb, corroborated boolean); "
               "INSERT INTO telemetry_detection VALUES (1, '{\"rule\": 942100}', true)", database)
    monkeypatch.setenv("CR_STORE_EXEC", way_in(name, database))

    backed_up(monkeypatch, tmp_path)
    printed = capsys.readouterr().out
    [kept] = (tmp_path / "backups").iterdir()
    assert kept.name.startswith("store-") and kept.name.endswith(".pgdump") and str(kept) in printed
    assert kept.read_bytes().startswith(b"PGDMP")
    assert "users                     2" in printed and "detections                1" in printed

    psql(name, "INSERT INTO auth_user (username) VALUES ('after'); DROP TABLE telemetry_detection; "
               "CREATE TABLE stray (id int)", database)
    backed_up(monkeypatch, tmp_path, "--restore", str(kept))

    assert psql(name, "SELECT string_agg(username, ',' ORDER BY id) FROM auth_user", database) == "staff,learner"
    assert psql(name, "SELECT raw->>'rule', corroborated FROM telemetry_detection", database) == "942100|t"
    assert psql(name, "SELECT to_regclass('stray') IS NULL", database) == "t"
    assert psql(name, "INSERT INTO auth_user (username) VALUES ('next') RETURNING id", database) == "3", (
        "the identity sequence came back with the rows, so the next account does not collide")


def test_an_empty_store_keeps_no_backup_and_removes_none(store, monkeypatch, tmp_path, capsys):
    name, _ = store
    database = fresh_database(name)
    psql(name, "CREATE TABLE auth_user (id bigint PRIMARY KEY)", database)
    monkeypatch.setenv("CR_STORE_EXEC", way_in(name, database))
    older = tmp_path / "backups" / "store-20261001T000000Z.pgdump"
    older.parent.mkdir()
    older.write_bytes(b"PGDMP")

    backed_up(monkeypatch, tmp_path)

    assert sorted(path.name for path in older.parent.iterdir()) == [older.name]
    assert "holds no rows" in capsys.readouterr().out


def test_a_restore_that_fails_leaves_the_store_as_it_was(store, monkeypatch, tmp_path):
    name, _ = store
    database = fresh_database(name)
    psql(name, "CREATE TABLE auth_user (id bigint PRIMARY KEY); INSERT INTO auth_user VALUES (7)", database)
    monkeypatch.setenv("CR_STORE_EXEC", way_in(name, database))
    broken = tmp_path / "store-20261126T000000Z.pgdump"
    broken.write_bytes(b"PGDMP" + b"\x00" * 64)

    with pytest.raises(SystemExit, match="was not restored"):
        backed_up(monkeypatch, tmp_path, "--restore", str(broken))

    assert psql(name, "SELECT id FROM auth_user", database) == "7"


def platform_store(path, environ):
    done = subprocess.run([sys.executable, "manage.py", "migrate", "--noinput"], cwd=PLATFORM,
                          env={**environ, "CR_DB_HOST": "", "DJANGO_DB_PATH": str(path)},
                          capture_output=True, text=True)
    assert done.returncode == 0, done.stderr[-2000:]
    with closing(sqlite3.connect(path)) as db:
        db.execute("INSERT INTO auth_user (password, is_superuser, username, first_name, last_name, email, "
                   "is_staff, is_active, date_joined) VALUES ('x', 1, 'staff', '', '', '', 1, 1, "
                   "'2026-11-25 04:22:48.123456')")
        db.execute("INSERT INTO django_session (session_key, session_data, expire_date) "
                   "VALUES ('k', ?, '2026-11-26 00:00:00')", ("a\x00b",))
        db.commit()
        return {table: db.execute(f'SELECT count(*) FROM "{table}"').fetchone()[0]
                for (table,) in db.execute("SELECT name FROM sqlite_master WHERE type = 'table' "
                                           "AND name NOT LIKE 'sqlite_%' AND name != 'django_migrations'")}


def test_the_sqlite_store_is_loaded_into_postgresql_row_for_row_and_the_backup_is_not_touched(store, tmp_path):
    name, port = store
    database = fresh_database(name)
    environ = {key: value for key, value in os.environ.items() if not key.startswith("CR_DB_")}
    backup = tmp_path / "db-20261125T042248Z.sqlite3"
    counts = platform_store(backup, environ)
    before = backup.read_bytes()
    pg = {**environ, "CR_DB_HOST": "127.0.0.1", "CR_DB_PORT": port, "CR_DB_NAME": database,
          "CR_DB_PASSWORD": PASSWORD}

    done = subprocess.run([sys.executable, "manage.py", "load_sqlite_store", str(backup)], cwd=PLATFORM, env=pg,
                          capture_output=True, text=True)

    assert done.returncode == 0, done.stderr[-2000:]
    assert backup.read_bytes() == before
    for table, rows in counts.items():
        assert psql(name, f'SELECT count(*) FROM "{table}"', database) == str(rows), table
    assert psql(name, "SELECT is_superuser, date_joined FROM auth_user WHERE username = 'staff'", database) == (
        "t|2026-11-25 04:22:48.123456+00")
    assert psql(name, "SELECT session_data FROM django_session", database) == "ab", (
        "PostgreSQL text holds no NUL; the load drops the character and says so")
    assert "lost a NUL character" in done.stdout
    assert psql(name, "INSERT INTO auth_user (password, is_superuser, username, first_name, last_name, email, "
                      "is_staff, is_active, date_joined) VALUES ('x', false, 'next', '', '', '', false, true, now()) "
                      "RETURNING id", database) == str(counts["auth_user"] + 1)
